"""Парсер класса (9/10/11) из названия рассылки. Реализуется на Этапе 3."""

import re

GRADE_RE = re.compile(r"\b(9|10|11)\s*(?:кл|класс)", re.IGNORECASE)


def parse_grades(title: str) -> list[int]:
    """Возвращает список классов, упомянутых в названии рассылки.

    Пусто — рассылка не привязана к классу (общая).
    Несколько — рассылка одна на несколько классов (например, 9-11).
    """
    grades = {int(m.group(1)) for m in GRADE_RE.finditer(title)}
    # TODO(этап 3): добить логику диапазонов «9-11», «9–11» и крайних случаев
    return sorted(grades)
